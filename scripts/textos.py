def entry(text):
    names = re.findall(r"\{(\w+)\}", text)
    if not names:
        return {"message": text}
    message = text
    placeholders = {}
    for i, name in enumerate(names, 1):
        message = message.replace("{" + name + "}", f"${name.upper()}$")
        placeholders[name] = {"content": f"${i}"}
    return {"message": message, "placeholders": placeholders}


